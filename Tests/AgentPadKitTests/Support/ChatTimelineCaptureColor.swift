    static func bitmap(_ view: NSView) throws -> NSBitmapImageRep {
        XCTAssertEqual(view.window?.colorSpace, colorSpace, "Freeze the host before attaching capture content")
        let storage = try XCTUnwrap(view.bitmapImageRepForCachingDisplay(in: view.bounds))
        // Set the destination profile BEFORE drawing. Retagging an already
        // rendered bitmap would only mislabel display-dependent pixel values.
        let bitmap = try XCTUnwrap(storage.retagging(with: colorSpace))
        view.cacheDisplay(in: view.bounds, to: bitmap)
        return bitmap
    }
